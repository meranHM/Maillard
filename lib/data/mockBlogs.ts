// Helper function to find post by slug
export const findPostBySlug = (slug: string): BlogPost | undefined => {
  return MOCK_BLOG_POSTS.find(post => post.slug === slug)
}

// Helper function to filter posts
export const filterPosts = (filters: BlogFilters): BlogPost[] => {
  let filtered = [...MOCK_BLOG_POSTS]

  if (filters.category) {
    filtered = filtered.filter(post => 
      post.category.toLowerCase() === filters.category?.toLowerCase()
    )
  }

  if (filters.tag) {
    filtered = filtered.filter(post =>
      post.tags.some(tag => tag.toLowerCase() === filters.tag?.toLowerCase())
    )
  }

  if (filters.search) {
    const searchLower = filters.search.toLowerCase()
    filtered = filtered.filter(post =>
      post.title.toLowerCase().includes(searchLower) ||
      post.excerpt.toLowerCase().includes(searchLower)
    )
  }

  return filtered
}